function insumosFilas(items: ItemInsumo[]): ProductoSemilla[] {
  return items.map(([codigo, nombre, unidad, precio = 0]) => ({
    codigo,
    nombre,
    precio,
    categoria: "Ingredientes",
    unidad,
    tipo: "insumo",
  }));
}

